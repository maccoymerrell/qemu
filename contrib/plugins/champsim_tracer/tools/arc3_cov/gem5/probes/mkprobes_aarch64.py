def build(outdir):
    os.makedirs(outdir, exist_ok=True)
    made, failed = [], []
    for name, body in PROBES.items():
        src = os.path.join(outdir, name + '.S')
        with open(src, 'w') as fh:
            fh.write(HEAD + arena() + PRO + body + TAIL)
        elf = os.path.join(outdir, name)
        cmd = [CC, '-nostdlib', '-nostartfiles', '-static', '-no-pie',
               '-Wl,--build-id=none', '-march=armv8.4-a+lse+crc',
               '-o', elf, src]
        p = subprocess.run(cmd, stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT)
        if p.returncode != 0:
            failed.append((name, p.stdout.decode('utf-8', 'replace')))
        else:
            made.append(elf)
    return made, failed


if __name__ == '__main__':
    made, failed = build(sys.argv[1] if len(sys.argv) > 1
                         else os.path.join(HERE, 'aarch64'))
    for n, err in failed:
        sys.stderr.write('FAILED %s\n%s\n' % (n, err))
    print('\n'.join(made))
    sys.exit(1 if failed else 0)
