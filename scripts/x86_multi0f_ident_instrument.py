FUNC_RE = re.compile(r'^static void gen_multi0F\(')
INCLUDE_TAG = '/* multi0f_ident */'
# The FIRST line of the inserted block carries a marker of its own, so
# strip_instrumentation() can find the block's start as well as its end.
# A stripper that can only see the end leaves the prose behind and the
# next run inserts a second copy -- measured, not imagined.
INCLUDE_MARK = 'multi0f_ident: ENCODING-QUALIFIED IDENTITY'
INCLUDE_BLOCK = (
    '/*\n'
    ' * ' + INCLUDE_MARK + ' for the unconverted 0F spaces.\n'
    ' *\n'
    ' * gen_multi0F() is reached from five decode-table rows and\n'
    ' * dispatches on `b`, `s->modrm` and `s->prefix` to forty-one\n'
    ' * different instructions.  The table below states each arm as its\n'
    ' * own identity, so a consumer can tell `xgetbv` from `swapgs`.\n'
    ' * Generated by scripts/x86_multi0f_ident_instrument.py.\n'
    ' */\n'
    '#include "multi0f_ident.c.inc"  ' + INCLUDE_TAG)
CALL_TAG = '/* multi0f_ident */'
CALL = '    multi0f_ident_publish(b, modrm, prefixes);  ' + CALL_TAG

# Prefix classes, as gen_multi0F itself tests them.
