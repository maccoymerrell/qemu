#!/usr/bin/env python3
#
# Qualify the i386 `multi0F` rows -- five decode-table sites that answer
# for forty-one different instructions through forty-two arms.
#
# THE PROBLEM.  QEMU's new i386 decoder has not converted the 0F 00,
# 0F 01, 0F 1A, 0F 1B and 0F C7-group spaces, so each is one X86_OP_*
# site dispatching to one C function, gen_multi0F(), which then switches
# on the opcode and the modrm byte itself:
#
#     decode-new.c.inc  [0x00] = X86_OP_ENTRY1(multi0F, nop,v, nolea)
#     decode-new.c.inc  [0x01] = X86_OP_ENTRY1(multi0F, nop,v, nolea)
#     ...
#     translate.c       gen_multi0F()  switch (b) { ... switch (modrm) { ...
#
# One __LINE__ slot, one identity, for `sgdt`, `monitor`, `xgetbv`,
# `swapgs`, `rdtscp`, `invlpg` and the rest of the forty-one.  A consumer keyed on
# that identity cannot tell any of them apart, and the class the shared
# row states is the class of NONE of them: exec96 measured `xgetbv`
# published as GEN_OP_FENCE on its live encoding, because the word the
# generator has to work with is the placeholder name `multi0F`.
#
# THE DISCRIMINATOR IS NOT MISSING.  gen_multi0F() reads `b`, `s->modrm`
# and `s->prefix` and dispatches on exactly those; every arm below is one
# of ITS OWN case labels, and the word is the one QEMU wrote in the
# comment beside it.  This script carries those three facts into the
# identity, in the shape scripts/x86_x87_ident_instrument.py,
# scripts/x86_vex_ident_instrument.py and scripts/x86_cet_ident_instrument.py
# established:
#
#   * every arm's ANCHOR -- the QEMU source text that names it -- is
#     located in gen_multi0F()'s own body, and the script REFUSES if an
#     anchor is missing or matches twice.  The line it is found at is the
#     row's provenance, so a row can never outlive the arm it describes;
#
#   * the name is `translate.c/multi0F@b=<hex>,modrm=<bits>[,pfx=<name>]`
#     and the id is FNV-1a-32 of the NAME ALONE -- the derivation
#     scripts/x86_x87_ident_instrument.py and scripts/mips_ident_instrument.py
#     use, and for their reason: these arms share one X86_OP_ENTRY slot, so
#     there is no runtime __LINE__ to append, and appending the ANCHOR line
#     instead made every id a function of where translate.c happens to hold
#     the case label.  The anchor is still located, still refused when it is
#     missing or doubled, and still printed as the row's provenance;
#
#   * the selector is checked EXHAUSTIVELY over the whole (b, prefix,
#     modrm) space this function can be entered with -- not sampled -- and
#     the residual is reported beside the hits, because a selector that
#     answered for everything would pass a hits-only check;
#
#   * THE BASE ROWS DO NOT MOVE.  decode-new.c.inc is not touched at all.
#     translate.c gains an include and one call, both placed BELOW every
#     x87 leaf anchor and ABOVE gen_multi0F, and the script refuses if
#     that placement would renumber an x87 row.
#
# MACHINE STATE IS NOT A DISCRIMINATOR AND IS NOT USED AS ONE (R16).  The
# MPX arms are gated at run time on HF_MPX_EN_MASK, and a machine with
# MPX off executes `bndcl` as a no-op; the ENCODING still names `bndcl`,
# so the arms are keyed on prefix and mod alone and a disabled machine
# publishes the same identity as an enabled one.
#
# Author: Maccoy Merrell.
import argparse
