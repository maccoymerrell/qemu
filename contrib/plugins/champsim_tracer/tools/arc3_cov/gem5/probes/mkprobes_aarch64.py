HERE = os.path.dirname(os.path.abspath(__file__))
CC = 'aarch64-linux-gnu-gcc'

HEAD = """\
// GENERATED by mkprobes_aarch64.py -- ARC 3 aarch64 execution probe
.section .data
.balign 64
.globl arena
arena:
"""

TAIL = """
.globl done
done:
  mov  x8, #93
  mov  x0, #0
  svc  #0
"""

PRO = """
.section .text
.globl _start
_start:
  adrp x20, arena
  add  x20, x20, :lo12:arena
"""


def arena(n=128, seed=0x1234):
    out, v = [], seed
    for _ in range(n):
        v = (v * 6364136223846793005 + 1442695040888963407) & ((1 << 64) - 1)
        out.append('  .quad 0x%016x' % v)
    return '\n'.join(out) + '\n'


