"""
Generate the aarch64 EXECUTION probes for the gem5 cross-check.

Every probe is a static ``-nostdlib`` non-PIE ELF whose data lives in a
``.data`` arena at a FIXED virtual address.  That is the whole trick that makes
an address comparison between two different simulators meaningful: the stack,
the auxv and the environment are laid out differently by gem5's SE-mode process
loader and by qemu-user, so any address derived from SP differs between the two
runs for reasons that have nothing to do with either tool's correctness.  An
address derived from a link-time symbol does not.  The probes therefore touch
the arena and never the stack.

The vocabulary is chosen against the OPEN rows of the aarch64 memop table, not
for breadth: the 738 UNACCOUNTED count rows are ``ld2``/``ld3``/``ld4``,
``ldp``/``stp`` and the ``ld1``/``st1`` multi-register forms, so those are here
in strength.

Author: Maccoy Merrell.
"""
import os
