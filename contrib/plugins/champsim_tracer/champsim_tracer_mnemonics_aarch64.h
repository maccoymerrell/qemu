/*
 * Reclassify writeback LDR / STR / LDP / STP variants as INT_ADD.
 *
 * Capstone uses the same instruction ID for "LDR Xd, [Xn]" and for
 * "LDR Xd, [Xn], #imm" / "LDR Xd, [Xn, #imm]!", so the static table
 * can only see the base mnemonic.  Writeback forms reclassify to
 * GEN_OP_INT_ADD: the opcode carries the instruction's SUBSTANTIAL
 * operation — the address-ALU work — while the LOAD/STORE side is
 * trivial from the core's view (its delay belongs to the consumer's
 * memory model, and the memop still rides in the trace via the QEMU
 * memory callbacks).  Same principle as x86 "add reg, (mem)" staying
 * INT_ADD.
 *
 * Writeback detection: on Capstone 6 the implicit regs_write list for
 * an AArch64 load/store carries EXACTLY the writeback base when
 * present (explicit destination operands are NOT duplicated there, and
 * no load/store writes flags), so any implicit write on a MEM-operand
 * instruction is the writeback.  An earlier revision instead compared
 * n_regs_write against the explicit REG-operand write count, assuming
 * explicit dsts also appear in regs_write — under Capstone 6 that
 * fired only for stores, so writeback LOADS kept GEN_OP_LOAD against
 * design intent.  (Asymmetry caught by probe_arm_writeback_addr.)
 */
static void refine_arm64_ldst_access(
    const struct qemu_plugin_insn_info *info, InsnFields *f)
{
    if (info->n_regs_write == 0) {
        return;
    }
    for (unsigned i = 0; i < info->n_operands; i++) {
        if (info->operands[i].type == QEMU_PLUGIN_OP_MEM) {
            f->opcode = GEN_OP_INT_ADD;
            return;
        }
    }
}

/*
 * Operand-agnostic scalar-FP vs SIMD-vector promotion.
 *
 * A single Capstone AArch64 insn id covers both the scalar-FP form
 * (FDIV Dd, Dn, Dm) and the packed-vector form (FDIV Vd.2D, Vn.2D,
 * Vm.2D) — same mnemonic, same id — so the static mnemonic table can
 * only pick one family.  It picks the scalar FP_* op; this refiner
 * promotes it to the VEC_* twin when the decoded operands show a real
 * vector arrangement, i.e. some register operand carries a non-zero
 * Capstone lane width (scalar SS/SD/D/S forms have lane_bytes == 0;
 * NEON/SVE arrangements have it set).  Promotion only — a pure-scalar
 * use is left as the statically-classified FP_* op.  Runs once per
 * unique PC at template-build time, never on the hot path.
 */
static void refine_arm64_fp_vec(
    const struct qemu_plugin_insn_info *info, InsnFields *f)
{
    uint8_t promoted;
    switch (f->opcode) {
    case GEN_OP_FP_ADD:  promoted = GEN_OP_VEC_ADD;  break;
    case GEN_OP_FP_SUB:  promoted = GEN_OP_VEC_SUB;  break;
    case GEN_OP_FP_MUL:  promoted = GEN_OP_VEC_MUL;  break;
    case GEN_OP_FP_DIV:  promoted = GEN_OP_VEC_DIV;  break;
    case GEN_OP_FP_SQRT: promoted = GEN_OP_VEC_SQRT; break;
    case GEN_OP_FP_MADD: promoted = GEN_OP_VEC_MADD; break;
    case GEN_OP_FP_MSUB: promoted = GEN_OP_VEC_MSUB; break;
    case GEN_OP_FP_MOV:  promoted = GEN_OP_VEC_MOV;  break;
    default: return;
    }
    for (unsigned i = 0; i < info->n_operands; i++) {
        const qemu_plugin_operand *op = &info->operands[i];
        if (op->type == QEMU_PLUGIN_OP_REG && op->lane_bytes != 0) {
            f->opcode = promoted;
            return;
        }
    }
}

/*
 * THE FLAG-ONLY SHAPE.  A flag-writing form whose destination register
 * is XZR (or WZR for 32-bit forms) keeps nothing in the regfile: the
 * result is discarded and only NZCV survives.  AArch64 gives three of
 * these assembler alias mnemonics -- CMP / CMN / TST for SUBS / ADDS /
 * ANDS -- and does NOT give one to `bics xzr, xn, xm`, which has the
 * identical shape.  This refiner is named for the aliases but does not
 * read one: the detection below is the DESTINATION SET, so BICS is in
 * scope too and is in CMP_ALIAS_PROMOTE_INSNS for that reason (it is
 * also the second form of QEMU's own ANDS_r rule, so gating on the
 * alias list left that rule's identity row unresolvable).  Capstone
 * returns the underlying SUBS/ADDS/ANDS/BICS insn id (the assembler
 * mnemonic alias is just the disasm string), and
 * recent Capstone versions resolve the alias by dropping XZR from
 * the explicit operand list — only the implicit NZCV write remains,
 * so the walker's dst_regs[] for a `cmp` ends up containing just
 * REG_FLAGS.  Older Capstone (and the canonical `subs xzr, ...`
 * form) instead exposes XZR explicitly and the walker adds REG_ZERO
 * to dst_regs[]; both shapes are recognised below.
 *
 * Detection: every dst_regs[] entry must be REG_FLAGS or REG_ZERO
 * (or the array is empty if implicit-regs weren't folded in for some
 * reason).  Any other register destination means the assembler
 * wrote a real arithmetic result — keep the canonical SUBS/ADDS/ANDS
 * opcode.
 *
 * REG_ZERO is NOT stripped after promotion.  It used to be, so that
 * the per-insn shape matched the assembler-visible mnemonic — but the
 * mnemonic is the printed alias and the destination set is a statement
 * about the regfile, and matching one to the other is a convention
 * rather than a fact.  REG_ZERO exists in the generic space and the
 * instruction names it, so it is recorded; the opcode still promotes
 * to GEN_OP_CMP / GEN_OP_TEST, which is what carries the "this is a
 * compare" fact.  disas/capstone.c restores the same destination at
 * the boundary for the alias spellings Capstone hides it from (see
 * cap_aarch64_restore_alias_zero_reg); stripping it here would have
 * undone that repair one layer up.
 */
static void refine_arm64_cmp_alias(
    const struct qemu_plugin_insn_info *info, InsnFields *f)
{
    (void)info;
    for (uint8_t d = 0; d < f->n_dst_regs; d++) {
        if (f->dst_regs[d] == REG_FLAGS) continue;
        if (f->dst_regs[d] == REG_ZERO) continue;
        /* A real register destination — assembler didn't use the
         * XZR alias.  Keep the canonical SUBS/ADDS/ANDS opcode. */
        return;
    }
    switch (f->opcode) {
    case GEN_OP_INT_SUB:    /* SUBS xzr, ...  -> CMP */
    case GEN_OP_INT_ADD:    /* ADDS xzr, ...  -> CMN; same flag-only
                             * shape, mapped to CMP since there's no
                             * dedicated GEN_OP_CMN. */
        f->opcode = GEN_OP_CMP;
        break;
    case GEN_OP_AND:        /* ANDS xzr, ... -> TST; BICS xzr, ...
                             * is the same discard-and-keep-flags
                             * shape and has no alias mnemonic of its
                             * own, so it maps here too. */
        f->opcode = GEN_OP_TEST;
        break;
    default:
        return;
    }
}

/*
 * AArch64 system-operation split: DC / IC / AT / TLBI out of SYS.
 *
 * Capstone gives the whole SYS alias space one instruction id
 * (AARCH64_INS_SYS), so the static table can only name one class for all
 * of it.  It names cache maintenance, which is right for every member
 * but one.  The exception is DC ZVA (and its MTE sibling DC GZVA), which
 * is not maintenance at all: it zeroes a naturally aligned block of
 * memory whose size is DCZID_EL0.BS, i.e. it is a block STORE.  Linux
 * builds clear_page() on it, so on a system-mode trace it carries a
 * large share of all store traffic, and classifying it as anything that
 * cannot write memory silently mis-attributes that traffic.
 *
 * The discriminator is the operand shape, not the mnemonic string.
 * disas/capstone.c recognises the block-zeroing operations from
 * Capstone's structured sysop detail (sysop.sub_type == AARCH64_OP_DC
 * with sysop.alias.dc == AARCH64_DC_ZVA / _GZVA) and presents their Xt
 * operand as the written memory operand it really is.  No other SYS
 * operation gets a written MEM operand, because none of the others moves
 * architectural data, so seeing one here is exactly the signal.
 *
 * The rest keep the family's static class except the two that are not
 * cache maintenance: TLBI is TLB maintenance, and AT (address
 * translation) writes only PAR_EL1 and is ordered like a barrier.
 * Capstone prints the alias as the mnemonic ("dc", "ic", "at", "tlbi"),
 * or leaves it "sys" for an encoding it does not resolve to an alias,
 * which keeps the family default.
 */
static void refine_arm64_sysop(
    const struct qemu_plugin_insn_info *info, InsnFields *f)
{
    for (unsigned i = 0; i < info->n_operands; i++) {
        const qemu_plugin_operand *op = &info->operands[i];
        if (op->type == QEMU_PLUGIN_OP_MEM &&
            (op->access & QEMU_PLUGIN_OP_ACC_WRITE)) {
            /* DC ZVA / DC GZVA — a block store. */
            f->opcode = GEN_OP_STORE;
            return;
        }
    }
    if (!strcmp(info->mnemonic, "tlbi")) {
        f->opcode = GEN_OP_TLB_FLUSH;
    } else if (!strcmp(info->mnemonic, "at")) {
        f->opcode = GEN_OP_FENCE;
    }
}

